"""Keyframes built FROM character reference images, then image-to-video with Kling 3 'elements'.

Two layers of consistency:
  1. Each shot's keyframe is generated by an image-edit model that receives the
     reference images of every character in the shot.
  2. The video model also receives those reference sheets as 'elements', so faces
     and outfits don't drift while the characters move.
"""
from __future__ import annotations

import json
import math
import re
import textwrap
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

from . import cast
from .common import APIError, Job, download, env, http, log, run_ffmpeg

QUEUE = "https://queue.fal.run"


def fal_run(model: str, payload: dict, poll: float = 4.0, timeout: float = 1500) -> dict:
    """Submit to fal's queue, wait for completion, return the result JSON."""
    headers = {"Authorization": f"Key {env('FAL_KEY')}", "Content-Type": "application/json"}
    sub = http("POST", f"{QUEUE}/{model}", headers=headers, json=payload).json()
    status_url, response_url = sub["status_url"], sub["response_url"]
    t0 = time.time()
    while True:
        st = http("GET", status_url, headers=headers).json()
        status = st.get("status")
        if status == "COMPLETED":
            break
        if status not in ("IN_QUEUE", "IN_PROGRESS"):
            raise APIError(f"fal job {sub.get('request_id')} ended with status {status}: {st}")
        if time.time() - t0 > timeout:
            raise APIError(f"fal job {sub.get('request_id')} timed out")
        time.sleep(poll)
    return http("GET", response_url, headers=headers).json()


def clip_seconds(cfg: dict, needed: float) -> int:
    v = cfg["video"]
    return int(min(max(math.ceil(needed + 0.3), v["min_clip_seconds"]), v["max_clip_seconds"]))


def shot_cast(cfg: dict, shot: dict) -> list[cast.Character]:
    return [cast.Character(cfg, cid) for cid in shot.get("characters", [])]


def speakers_in_shot(shot: dict, chars: list[cast.Character]) -> list[str]:
    ids = {c.id for c in chars}
    return [c.name for c in chars if any(l["speaker"] == c.id for l in shot["lines"]) and c.id in ids]


def keyframe_prompt(script: dict, shot: dict, chars: list[cast.Character], style: str) -> str:
    who = " ".join(f"Image {i + 1} shows {c.name} ({c.look})." for i, c in enumerate(chars))
    keep = " Keep every character's face, hair, body, outfit and colours exactly as in their reference image." if chars else ""
    return (f"{who} New scene: {shot['image_prompt']}. Setting: {script.get('setting', '')}.{keep} "
            f"Style: {style}. Vertical 9:16 cinematic frame, expressive faces, no text, no captions, no watermark.")


def motion_prompt(shot: dict, chars: list[cast.Character], style: str, use_elements: bool) -> str:
    p = shot["motion_prompt"]
    talking = speakers_in_shot(shot, chars)
    if talking:
        p += f". {' and '.join(talking)} {'is' if len(talking) == 1 else 'are'} talking with natural expressions and gestures"
    if use_elements and chars:
        for i, c in enumerate(chars):
            p = re.sub(rf"\b{re.escape(c.name)}\b", f"@Element{i + 1}", p)
        p += ". " + ", ".join(f"@Element{i + 1} is {c.name}" for i, c in enumerate(chars))
    return f"{p}. {style}. Smooth motion, consistent faces."


# ---------------------------------------------------------------- real providers
def make_shot(cfg: dict, job: Job, script: dict, i: int, needed: float, style: str) -> Path:
    shot = script["shots"][i]
    img_path, clip_path = job.path(f"shot{i:02d}_key.png"), job.path(f"shot{i:02d}_clip.mp4")
    if clip_path.exists():
        return clip_path
    img_cfg, vid_cfg = cfg["images"], cfg["video"]
    chars = [c for c in shot_cast(cfg, shot) if c.has_refs]
    refs = {c.id: cast.ref_urls(c) for c in chars}

    img_url = shot.get("image_url")
    if not img_path.exists() or not img_url:
        prompt = keyframe_prompt(script, shot, chars, style)
        if chars:
            res = fal_run(img_cfg["edit"], {"prompt": prompt, "image_urls": [refs[c.id]["front"] for c in chars],
                                            "aspect_ratio": img_cfg["aspect_ratio"], "num_images": 1})
        else:
            res = fal_run(img_cfg["text_to_image"], {"prompt": prompt, "aspect_ratio": img_cfg["aspect_ratio"], "num_images": 1})
        img_url = res["images"][0]["url"]
        download(img_url, img_path)
        shot["image_url"] = img_url
        job.add_cost(img_cfg["price_per_image"])

    secs = clip_seconds(cfg, needed)
    use_el = vid_cfg.get("use_elements", True) and bool(chars)
    payload = {
        "start_image_url": img_url,
        "prompt": motion_prompt(shot, chars, style, use_el),
        "duration": str(secs),
        "generate_audio": vid_cfg["generate_audio"],
        "negative_prompt": vid_cfg["negative_prompt"],
        "cfg_scale": vid_cfg["cfg_scale"],
    }
    if use_el:
        payload["elements"] = [{"frontal_image_url": refs[c.id]["front"], "reference_image_urls": [refs[c.id]["side"]]} for c in chars]
    res = fal_run(vid_cfg["model"], payload)
    download(res["video"]["url"], clip_path)
    job.add_cost(secs * vid_cfg["price_per_second"])
    log.info("  shot %d ready (%ss, %s)", i + 1, secs, ", ".join(c.name for c in chars) or "no characters")
    return clip_path


# ---------------------------------------------------------------- mock provider: storyboard animatic
def _esc(t: str) -> str:
    return t.replace("\\", "\\\\").replace(":", "\\:").replace("'", "’").replace("%", "\\%").replace(",", "\\,")


def make_shot_mock(cfg: dict, job: Job, script: dict, i: int, needed: float, style: str) -> Path:
    """Storyboard frame: the characters' reference cards + the shot description, with a slow zoom."""
    shot = script["shots"][i]
    img_path, clip_path = job.path(f"shot{i:02d}_key.png"), job.path(f"shot{i:02d}_clip.mp4")
    if clip_path.exists():
        return clip_path
    W, H = cfg["render"]["width"], cfg["render"]["height"]
    chars = [c for c in shot_cast(cfg, shot) if c.has_refs]
    desc = _esc("\n".join(textwrap.wrap(shot["image_prompt"], 38)[:7]))
    inputs = ["-f", "lavfi", "-i", f"color=c=0x1b1f2a:s={W}x{H}"]
    graph, last = [], "[0:v]"
    n = len(chars)
    cw = 300 if n <= 2 else 260
    for k, c in enumerate(chars):
        inputs += ["-i", str(c.front)]
        x = (W - n * cw - (n - 1) * 30) // 2 + k * (cw + 30)
        graph.append(f"[{k + 1}:v]scale={cw}:-2[c{k}]")
        graph.append(f"{last}[c{k}]overlay={x}:330[o{k}]")
        last = f"[o{k}]"
    graph.append(f"{last}drawtext=text='SHOT {i + 1}  ·  STORYBOARD (mock)':fontcolor=white@0.7:fontsize=40:x=(w-tw)/2:y=200,"
                 f"drawtext=text='{desc}':fontcolor=white:fontsize=44:line_spacing=14:x=(w-tw)/2:y={330 + (int(cw * 16 / 9) if n else 0) + 60}[out]")
    run_ffmpeg([*inputs, "-filter_complex", ";".join(graph), "-map", "[out]", "-frames:v", "1", str(img_path)])
    secs = clip_seconds(cfg, needed)
    run_ffmpeg(["-loop", "1", "-i", str(img_path), "-vf",
                f"zoompan=z='min(zoom+0.0006,1.08)':d=1:s={W}x{H}:fps=30,format=yuv420p",
                "-t", str(secs), "-c:v", "libx264", "-preset", "veryfast", "-crf", "23", str(clip_path)])
    return clip_path


# ---------------------------------------------------------------- driver
def make_all_shots(cfg: dict, job: Job, script: dict, timing: dict, style: str, mock: bool = False) -> list[Path]:
    fn = make_shot_mock if mock else make_shot
    n = len(script["shots"])
    workers = 1 if mock else cfg["video"]["parallel_jobs"]
    log.info("Generating %d shot(s) with %s ...", n, "storyboard mock" if mock else cfg["video"]["model"])
    errors = {}
    with ThreadPoolExecutor(max_workers=workers) as pool:
        futs = {pool.submit(fn, cfg, job, script, i, timing["shots"][i]["duration"], style): i for i in range(n)}
        for f in as_completed(futs):
            try:
                f.result()
            except Exception as e:
                errors[futs[f]] = str(e)
                log.error("  shot %d failed: %s", futs[f] + 1, e)
    job.path("script.json").write_text(json.dumps(script, indent=2, ensure_ascii=False), "utf-8")
    if errors:
        raise RuntimeError(f"{len(errors)} shot(s) failed: {sorted(k + 1 for k in errors)}. "
                           f"Fix and re-run: python run.py resume {job.id}")
    return [job.path(f"shot{i:02d}_clip.mp4") for i in range(n)]
